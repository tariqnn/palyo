const sportTokens:Record<string,string>={football:"كرة القدم",basketball:"كرة السلة",dodgeball:"دودج بول",tennis:"التنس",padel:"البادل",fitness:"اللياقة",volleyball:"كرة الطائرة",badminton:"الريشة الطائرة",kayaking:"التجديف",hiking:"المشي الجبلي",climbing:"التسلق"};
const dateTokens:Record<string,string>={Mon:"الاثنين",Tue:"الثلاثاء",Wed:"الأربعاء",Thu:"الخميس",Fri:"الجمعة",Sat:"السبت",Sun:"الأحد",Jan:"يناير",Feb:"فبراير",Mar:"مارس",Apr:"أبريل",May:"مايو",Jun:"يونيو",Jul:"يوليو",Aug:"أغسطس",Sep:"سبتمبر",Oct:"أكتوبر",Nov:"نوفمبر",Dec:"ديسمبر",AM:"ص",PM:"م"};

export function translateArabic(value: string) {
  const clean = value.trim();
  if (!clean) return value;
  const exact = arabicText[clean];
  if (exact) return value.replace(clean, exact);
  for (const [pattern, render] of arabicPatterns) {
    const match = clean.match(pattern);
    if (match) return value.replace(clean, render(...match.slice(1)));
  }
  if (/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun),/.test(clean)) {
    return value.replace(clean, clean.replace(/\b(Mon|Tue|Wed|Thu|Fri|Sat|Sun|Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec|AM|PM)\b/g, token=>dateTokens[token]||token));
  }
  if (/^(football|basketball|dodgeball|tennis|padel|fitness|volleyball|badminton|kayaking|hiking|climbing)(?:\s|·|$)/i.test(clean)) {
    const next=clean.replace(/\b(football|basketball|dodgeball|tennis|padel|fitness|volleyball|badminton|kayaking|hiking|climbing)\b/gi,token=>sportTokens[token.toLowerCase()]||token).replace(/Team Game/gi,"مباراة جماعية").replace(/Doubles/gi,"زوجي").replace(/Singles/gi,"فردي");
    return value.replace(clean,next);
  }
  return value;
}

